import { db, storage } from 'hatchable';
import { sha256Hex } from 'lib/cac-director-security.js';
import { enforcePublicRateLimit } from 'lib/cac-public-rate-limit.js';
export const access = 'public';
export const methods = ['POST'];
export default async function(req,res){
  res.setHeader('Cache-Control','no-store, no-cache, must-revalidate, private');
  res.setHeader('Pragma','no-cache');
  res.setHeader('Referrer-Policy','no-referrer');
  res.setHeader('X-Content-Type-Options','nosniff');
  const token=String(req.body?.token||'').trim();
  if(token.length<32 || token.length>256) return res.status(400).json({error:'Invalid invite token'});
  if(!(await enforcePublicRateLimit(req,res,'cac-document',token,10))) return res.status(429).json({error:'Too many document requests. Try again later.'});
  const file=req.files?.find(f=>f.field==='document');
  if(!token || !file) return res.status(400).json({error:'Invite token and ID document are required'});
  const tokenHash=await sha256Hex(token);
  const {rows}=await db.query(`SELECT i.id AS "inviteId", i.status, i.expires_at AS "expiresAt", d.id AS "directorId", d.id_document_status AS "idDocumentStatus" FROM cac_director_invites i JOIN cac_director_profiles d ON d.id=i.director_id WHERE i.token_hash=$1 LIMIT 1`,[tokenHash]);
  if(!rows.length) return res.status(404).json({error:'Invite not found'});
  if(rows[0].idDocumentStatus==='submitted') return res.status(409).json({error:'An identity document has already been submitted for this invitation'});
  if(!['pending','opened','sent'].includes(rows[0].status)) return res.status(409).json({error:'This invitation is no longer active'});
  if(new Date(rows[0].expiresAt)<=new Date()) return res.status(410).json({error:'This invitation has expired'});
  const allowed=['image/jpeg','image/png','application/pdf'];
  if(!allowed.includes(file.contentType)) return res.status(415).json({error:'Upload a PDF, JPG or PNG'});
  if(file.buffer.length>8*1024*1024) return res.status(413).json({error:'Maximum document size is 8MB'});
  const head=Array.from(file.buffer.slice(0,8));
  const pdf=head.length>=5 && String.fromCharCode(...head.slice(0,5))==='%PDF-';
  const png=head.length>=8 && head.join(',')==='137,80,78,71,13,10,26,10';
  const jpeg=head.length>=3 && head[0]===255 && head[1]===216 && head[2]===255;
  if((file.contentType==='application/pdf'&&!pdf)||(file.contentType==='image/png'&&!png)||(file.contentType==='image/jpeg'&&!jpeg)) return res.status(415).json({error:'Document content does not match the declared file type'});
  const fileHash=await sha256Hex(file.buffer);
  const safeName=String(file.filename||'id-document').replace(/[^a-zA-Z0-9._-]/g,'_').slice(0,180) || 'id-document';
  const key=`cac/directors/${rows[0].directorId}/${fileHash}-${safeName}`;
  const url=await storage.put(key,file.buffer,file.contentType);
  await db.query(`UPDATE cac_director_profiles SET id_document_url=$1,id_document_name=$2,id_document_hash=$3,id_document_status='submitted',updated_at=now() WHERE id=$4`,[url,file.filename,fileHash,rows[0].directorId]);
  await db.query(`INSERT INTO cac_director_audit_events (director_id,invite_id,event_type,actor,metadata) VALUES ($1,$2,'id_document_submitted','invitee',$3)`,[rows[0].directorId,rows[0].inviteId,JSON.stringify({filename:file.filename,contentType:file.contentType,sha256:fileHash})]);
  res.json({ok:true,status:'submitted',filename:file.filename});
}