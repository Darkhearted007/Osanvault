  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  candidate_match_id uuid NOT NULL,
  previous_status text NOT NULL,
  proposed_status text NOT NULL,
  final_decision text NOT NULL CHECK (final_decision IN ('CERTIFICATION_ELIGIBLE','REVIEW_APPROVED_BUT_NOT_CERTIFICATION_ELIGIBLE','REVIEW_REQUIRED','EVIDENCE_INSUFFICIENT','EVIDENCE_CONFLICT','EVIDENCE_REJECTED','EVIDENCE_UNVERIFIED','GEOGRAPHY_UNVERIFIED','GEOGRAPHY_CONFLICT','GEOMETRY_INVALID')),
  phase39118_decision text,
  phase39119_review_state text,
  review_decision text,
  evidence_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
  artifact_id text,
  artifact_sha256 text,
  canonical_source text,
  parser_version text,
  validation_version text,
  provenance_reference jsonb,
  geometry_source text,
  geometry_record_id text,
  crosswalk_id text,
  policy_version text NOT NULL,
  certification_algorithm_version text NOT NULL,
  gate_results jsonb NOT NULL DEFAULT '[]'::jsonb,
  failed_gates jsonb NOT NULL DEFAULT '[]'::jsonb,
  evidence_chain jsonb NOT NULL DEFAULT '{}'::jsonb,
  validation_errors jsonb NOT NULL DEFAULT '[]'::jsonb,
  deterministic_fingerprint text NOT NULL,
  candidate_mutation boolean NOT NULL DEFAULT false,
  geometry_mutation boolean NOT NULL DEFAULT false,
  evidence_mutation boolean NOT NULL DEFAULT false,
  audit_id uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (deterministic_fingerprint)
) ;